#!/usr/bin/env python3
"""Generate the small platform adapters from shared/product.json (Python 3.5+)."""
from __future__ import print_function, unicode_literals

import argparse
from collections import OrderedDict
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent


def release_version(value):
    if not isinstance(value, str) or not re.fullmatch(r'\d+\.\d+\.\d+(?:-[a-z0-9.-]+)?', value):
        raise ValueError('Use a semantic version such as 0.10.1')
    return value


def product(root=ROOT):
    with (root / 'shared/product.json').open(encoding='utf-8') as stream:
        data = json.load(stream)
    release_version(data['version'])
    if set(data['protocols']) != set(data['default_ports']):
        raise ValueError('Every stored protocol needs a default port')
    if data['session_schema_version'] != 2:
        raise ValueError('A schema change requires explicit migration work on both platforms')
    return data


def set_version(version, root=ROOT):
    version = release_version(version)
    data = product(root)
    data['version'] = version
    (root / 'shared/product.json').write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def generated_files(root=ROOT):
    data = product(root)
    values = [('VERSION', data['version']), ('SESSION_SCHEMA_VERSION', data['session_schema_version']),
              ('PROTOCOLS', tuple(data['protocols'])), ('DEFAULT_PORTS', data['default_ports']),
              ('GROUP_SSH_FIELDS', tuple(data['group_ssh_fields'])),
              ('VAULT_PARAMETERS', data['vault_parameters']),
              ('BACKUP_PARAMETERS', data['backup_parameters']),
              ('UPDATE_PARAMETERS', data['update_parameters']),
              ('SFTP_CHMOD_SCRIPT', (root / 'shared/sftp-chmod.py').read_text(encoding='utf-8'))]
    result = {}
    if (root / 'astraterm').is_dir():
        lines = ['# Generated by tools/sync_shared.py. Edit shared/product.json instead.',
                 'from __future__ import unicode_literals', '']
        for name, value in values:
            # ASCII-only output remains importable by Python 3.5 without a codec header.
            if name == 'DEFAULT_PORTS':
                encoded = '{' + ', '.join('{!r}: {!r}'.format(key, value[key]) for key in data['protocols']) + '}'
            elif isinstance(value, dict):
                encoded = '{' + ', '.join('{!r}: {!r}'.format(key, value[key]) for key in sorted(value)) + '}'
            else:
                encoded = repr(value)
            lines.append('{} = {}'.format(name, encoded))
        result[root / 'astraterm/_shared.py'] = '\n'.join(lines) + '\n'
    if (root / 'windows/src').is_dir():
        lines = ["'use strict';", '// Generated by tools/sync_shared.py. Edit shared/product.json instead.', '']
        for name, value in values:
            encoded = json.dumps(value, ensure_ascii=True, separators=(',', ':'), sort_keys=True)
            if isinstance(value, (tuple, list, dict)):
                encoded = 'Object.freeze({})'.format(encoded)
            lines.append('const {} = {};'.format(name, encoded))
        lines.append('module.exports = Object.freeze({ ' + ', '.join(name for name, unused in values) + ' });')
        result[root / 'windows/src/shared.cjs'] = '\n'.join(lines) + '\n'
        # The packaged GUI check consumes the same public vectors as Astra tests.
        for name, adapter in (('tabs', 'tab-contracts'), ('host-stats', 'host-stats-contract'),
                              ('file-drops', 'file-drop-contract'), ('keyboard-shortcuts', 'keyboard-shortcuts-contract')):
            source = 'shared/contracts/{}.json'.format(name)
            contract = root / source
            if contract.is_file():
                # Python 3.5 dict iteration order can differ between the build and test processes.
                vectors = json.loads(contract.read_text(encoding='utf-8'), object_pairs_hook=OrderedDict)
                result[root / 'windows/src/{}.cjs'.format(adapter)] = (
                    "'use strict';\n// Generated by tools/sync_shared.py from {}.\n".format(source) +
                    'module.exports = ' + json.dumps(vectors, ensure_ascii=True, indent=2) + ';\n')
    for relative in ('windows/package.json', 'windows/package-lock.json'):
        filename = root / relative
        if not filename.is_file():
            continue
        with filename.open(encoding='utf-8') as stream:
            document = json.load(stream)
        document['version'] = data['version']
        if relative.endswith('package-lock.json') and '' in document.get('packages', {}):
            document['packages']['']['version'] = data['version']
        result[filename] = json.dumps(document, ensure_ascii=False, indent=2) + '\n'
    return result


def synchronize(check=False, root=ROOT):
    stale = []
    for filename, expected in generated_files(root).items():
        actual = filename.read_text(encoding='utf-8') if filename.exists() else ''
        # Existing package formatting is irrelevant; version metadata is what matters.
        same = actual == expected
        if filename.name in ('package.json', 'package-lock.json') and actual:
            same = json.loads(actual) == json.loads(expected)
        if not same:
            stale.append(filename.relative_to(root).as_posix())
            if not check:
                filename.write_text(expected, encoding='utf-8')
    if stale and check:
        raise ValueError('Run python tools/sync_shared.py; stale: ' + ', '.join(stale))
    return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify without writing files')
    parser.add_argument('--version', help='Set the next shared release version and regenerate both adapters')
    args = parser.parse_args()
    try:
        if args.version:
            if args.check:
                raise ValueError('Use a semantic version without --check')
            set_version(args.version)
        changed = synchronize(args.check)
        print('Shared release {}: {}'.format(product()['version'], 'verified' if args.check else ', '.join(changed) or 'up to date'))
    except (ValueError, OSError) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
