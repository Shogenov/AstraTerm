'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const { createFixture } = require('../src/smoke-fixture.cjs');
const { TerminalManager } = require('../src/backend/terminal.cjs');
const { IdentityManager } = require('../src/backend/identities.cjs');
const { HostTrustStore } = require('../src/backend/host-trust.cjs');
const { FilesService } = require('../src/backend/files.cjs');

test('standalone GUI fixture authenticates encrypted RSA and serves all file operations on the terminal transport', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'astraterm-gui-fixture-'));
  const fixture = await createFixture(directory);
  let passphrases = 0;
  const prompt = async request => { if (request.kind === 'host-key') return true; if (request.kind === 'passphrase') { passphrases++; return fixture.passphrase; } throw new Error('Unexpected authentication method'); };
  const identities = new IdentityManager({ directory: path.join(directory, 'metadata'), agentPath: path.join(directory, 'nonexistent-agent'), prompt });
  identities.upsert({ name: 'Synthetic fixture', key_file: fixture.keyFile });
  const trust = new HostTrustStore({ directory: path.join(directory, 'metadata'), knownHostsPath: path.join(directory, 'nonexistent-known-hosts'), prompt });
  const manager = new TerminalManager({ identityManager: identities, trustStore: trust, prompt });
  const files = new FilesService({ terminals: manager });
  t.after(async () => { files.dispose(); manager.dispose(); identities.dispose(); await fixture.close(); fs.rmSync(directory, { recursive: true, force: true }); });
  const terminal = await manager.create(fixture.profilebase);
  const endpoint = { mode: 'sftp', terminalId: terminal.id };
  const listing = await files.list(endpoint);
  assert.equal(listing.path, '/');
  assert.deepEqual(listing.entries.map(item => item.name), ['logs', 'welcome.txt']);
  const welcome = await files.readText({ ...endpoint, path: '/welcome.txt' });
  assert.match(welcome.text, /Привет, Windows!/);
  await files.writeText({ ...endpoint, path: '/welcome.txt', text: 'Обновлено\n', revision: welcome.revision });
  assert.equal((await files.readText({ ...endpoint, path: '/welcome.txt' })).text, 'Обновлено\n');
  await files.mkdir({ ...endpoint, path: '/created' });
  await files.rename({ ...endpoint, path: '/created', targetPath: '/renamed' });
  await files.remove({ ...endpoint, path: '/renamed' });
  const data = crypto.randomBytes(150013);
  const source = path.join(directory, 'upload.bin');
  const destination = path.join(directory, 'download.bin');
  fs.writeFileSync(source, data);
  await files.upload({ ...endpoint, localPath: source, targetPath: '/upload.bin' });
  await files.download({ ...endpoint, remotePath: '/upload.bin', localPath: destination });
  assert.deepEqual(fs.readFileSync(destination), data);
  await files.remove({ ...endpoint, path: '/upload.bin' });
  assert.equal(fixture.counters.authenticated, 1);
  assert.equal(fixture.counters.subsystems, 1);
  assert.equal(fixture.counters.ptys.length, 1);
  assert.equal(passphrases, 1);
  manager.write(terminal.id, 'GUI_FIXTURE_MARKER\r');
  for (let attempt = 0; attempt < 100 && !fixture.counters.received.some(item => item.data.includes('GUI_FIXTURE_MARKER')); attempt++) await new Promise(resolve => setTimeout(resolve, 10));
  assert.equal(fixture.counters.received.some(item => item.clientId === 1 && item.data.includes('GUI_FIXTURE_MARKER')), true);
});
